# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

database_url = os.environ.get('DATABASE_URL', 'sqlite:///db.sqlite3')
database_url_parts = urlsplit(database_url)
if (
    database_url_parts.scheme != 'sqlite'
    or database_url_parts.netloc
    or database_url_parts.query
    or database_url_parts.fragment
):
    raise ImproperlyConfigured('DATABASE_URL debe ser una URL SQLite sin opciones adicionales.')

database_path = unquote(database_url_parts.path)
if not database_path or database_path == '/':
    raise ImproperlyConfigured('DATABASE_URL debe indicar la ruta de un archivo SQLite.')
if database_path == '/:memory:':
    database_name = ':memory:'
elif database_path.startswith('//'):
    database_name = Path(database_path[1:])
else:
    database_name = BASE_DIR / database_path.lstrip('/')

DATABASES = {
    'default': {
        'ENGINE': 'django.db.backends.sqlite3',
        'NAME': database_name,
    }
}


